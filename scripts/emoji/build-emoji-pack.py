#!/usr/bin/env python3
"""Build src/generated/emoji-pack.ts: Twemoji SVGs (jdecked/twemoji, graphics CC-BY 4.0) for every emoji without
skin-tone modifiers + emojibase-data (MIT) names/tags in English and Chinese for the icon picker search.
One deflate-raw blob, base64, decoded lazily in the plugin with DecompressionStream (works offline).
usage: python3 scripts/emoji/build-emoji-pack.py <twemoji-17.0.3>/assets/svg <emojibase-data package dir>"""
import json, os, re, sys, zlib, base64
svgdir, eb = sys.argv[1], sys.argv[2]
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'generated', 'emoji-pack.ts')
HEAD = re.compile(r'^<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36"( xml:space="preserve")?>')
def key(u):  # twemoji file name rule: drop FE0F unless the sequence has a ZWJ
    cps = [ord(c) for c in u]
    if 0x200D not in cps: cps = [c for c in cps if c != 0xFE0F]
    return '-'.join('%x' % c for c in cps)
svgs = {}
for f in sorted(os.listdir(svgdir)):
    if not f.endswith('.svg') or re.search(r'1f3f[b-f]', f): continue
    s = open(os.path.join(svgdir, f), encoding='utf8').read().strip()
    m = HEAD.match(s)
    svgs[f[:-4]] = s[m.end():-len('</svg>')] if m and s.endswith('</svg>') else '!' + s   # '!' = full document
en = {x['hexcode']: x for x in json.load(open(os.path.join(eb, 'en/compact.json'), encoding='utf8'))}
zh = {x['hexcode']: x for x in json.load(open(os.path.join(eb, 'zh/compact.json'), encoding='utf8'))}
lst = []; miss = 0
for hx, e in sorted(en.items(), key=lambda kv: kv[1].get('order', 1e9)):
    if 'group' not in e or e['group'] == 2: continue   # group 2 = skin-tone components
    k = key(e['unicode'])
    if k not in svgs: miss += 1; continue
    z = zh.get(hx, {})
    lst.append([e['unicode'], e['group'], e['label'], z.get('label', ''), ' '.join(e.get('tags', [])[:6]), ' '.join(z.get('tags', [])[:6])])
blob = json.dumps({'svg': svgs, 'list': lst}, ensure_ascii=False, separators=(',', ':')).encode()
c = zlib.compressobj(9, zlib.DEFLATED, -15); raw = c.compress(blob) + c.flush()
b64 = base64.b64encode(raw).decode()
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as fh:
    fh.write('// GENERATED by scripts/emoji/build-emoji-pack.py — do not edit.\n')
    fh.write('// Emoji graphics: Twemoji (c) Twitter, Inc and other contributors, jdecked/twemoji v17.0.3, CC-BY 4.0\n')
    fh.write('// https://creativecommons.org/licenses/by/4.0/ — names/keywords: emojibase-data (MIT) from Unicode CLDR.\n')
    fh.write('/*! Emoji graphics: Twemoji by Twitter, Inc and other contributors (jdecked/twemoji), licensed CC-BY 4.0 */\n')
    fh.write(f'export const EMOJI_COUNT = {len(svgs)};\nexport const EMOJI_PACK = "{b64}";\n')
print(f'svgs {len(svgs)}, picker entries {len(lst)} (no svg: {miss}), json {len(blob)} B, deflate {len(raw)} B, base64 {len(b64)} B')
